#!/usr/bin/env node
// Copy the ts-rs generated TypeScript from its staging directory into packages/shared,
// prettier-formatted, touching only files whose content actually changed.
//
// Usage:
//   node scripts/sync-ts-exports.js clean              empty the staging dir (before exporting)
//   node scripts/sync-ts-exports.js [--report-stale]   format + sync staged files into shared
//
// packages/mdbg/.cargo/config.toml points TS_RS_EXPORT_DIR at packages/mdbg/target/ts-rs, so
// `cargo test` never writes the committed files directly. That matters for two reasons:
// - ts-rs output is not prettier style (its own `format` feature uses dprint), so writing in
//   place left whitespace-only churn behind after every bare `cargo test`.
// - Rewriting a file with identical content still changes its mtime; the next `git status`
//   then rewrites .git/index, and packages/mdbg/build.rs (`rerun-if-changed=.git/index`)
//   recompiles the crate. Unchanged files are left alone here, so that stops.
//
// Callers clean the staging dir before exporting. Otherwise a type deleted from Rust would
// linger there and be copied back into shared after its .ts file was removed.
//
// Stale files (in shared but no longer generated) are only listed, never deleted, and only
// with --report-stale: after a filtered `cargo test` the staging dir holds just some of the
// types, so absence there does not mean the type is gone.
const fs = require("fs");
const path = require("path");
const prettier = require("prettier");

const ROOT = path.resolve(__dirname, "..");
const STAGING = path.join(ROOT, "packages", "mdbg", "target", "ts-rs");
const DEST = path.join(ROOT, "packages", "shared");
// Narrower than the project's 200 so type literals with many fields break across lines.
const PRINT_WIDTH = 120;

function listTs(dir, base = dir) {
    if (!fs.existsSync(dir)) {
        return [];
    }
    const out = [];
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            out.push(...listTs(full, base));
        } else if (entry.name.endsWith(".ts")) {
            out.push(path.relative(base, full));
        }
    }
    return out;
}

async function sync(reportStale) {
    const staged = listTs(STAGING);
    if (staged.length === 0) {
        console.error(`Error: no generated TypeScript in ${STAGING}.`);
        console.error("The ts-rs export tests did not run, or TS_RS_EXPORT_DIR points somewhere else.");
        process.exit(1);
    }

    let updated = 0;
    for (const rel of staged) {
        const dest = path.join(DEST, rel);
        const raw = fs.readFileSync(path.join(STAGING, rel), "utf8");
        // The API, not the CLI: .prettierignore lists target/, and the CLI silently skips
        // ignored paths. Config is resolved against the destination, as for the committed file.
        const options = (await prettier.resolveConfig(dest)) ?? {};
        const formatted = await prettier.format(raw, { ...options, printWidth: PRINT_WIDTH, filepath: dest });
        const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
        if (current !== formatted) {
            fs.mkdirSync(path.dirname(dest), { recursive: true });
            fs.writeFileSync(dest, formatted, "utf8");
            console.log(`${current === null ? "Added" : "Updated"}: packages/shared/${rel.split(path.sep).join("/")}`);
            updated++;
        }
    }
    console.log(`TypeScript exports: ${staged.length} generated, ${updated} changed.`);

    if (reportStale) {
        const stagedSet = new Set(staged);
        const dirs = new Set(staged.map((rel) => rel.split(path.sep)[0]));
        const stale = [...dirs].flatMap((d) => listTs(path.join(DEST, d), DEST)).filter((rel) => !stagedSet.has(rel));
        if (stale.length > 0) {
            console.warn("Warning: no longer generated by ts-rs (delete them if the Rust type is gone):");
            for (const rel of stale) {
                console.warn(`  - packages/shared/${rel.split(path.sep).join("/")}`);
            }
        }
    }
}

const args = process.argv.slice(2);
if (args[0] === "clean") {
    fs.rmSync(STAGING, { recursive: true, force: true });
} else {
    sync(args.includes("--report-stale")).catch((e) => {
        console.error(`Error syncing TypeScript exports: ${e.message}`);
        process.exit(1);
    });
}
